AppearancePrefAccess PrefAccess(Profile& profile) {
  return profile.IsRegularProfile() && !profile.IsOffTheRecord() &&
                 !profile.IsGuestSession()
             ? AppearancePrefAccess::kWritableProfile
             : AppearancePrefAccess::kReadOnlyProfile;
}

ThemeService::BrowserColorScheme ColorScheme(AppearanceTheme theme) {
  switch (theme) {
    case AppearanceTheme::kSystem:
      return ThemeService::BrowserColorScheme::kSystem;
    case AppearanceTheme::kLight:
      return ThemeService::BrowserColorScheme::kLight;
    case AppearanceTheme::kDark:
      return ThemeService::BrowserColorScheme::kDark;
  }
  return ThemeService::BrowserColorScheme::kSystem;
}

